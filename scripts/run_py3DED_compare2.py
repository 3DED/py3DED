# determine hkl indices of reflections to cover full intensity range from strongest to weakest
sort_by_intensity = np.argsort(int_bw.sum(dim='z').data)[::-1]
hkl_selection = sort_by_intensity[range(0,N_hkl, int(N_hkl/21))][:20]
hkl_selection[1] = sort_by_intensity[1] # strongest reflection that is not 000
hkl_selection[-1] = sort_by_intensity[-1] # weakest reflection

# min. number of points of rocking curve to show
minimum_range_to_show = 8.0   # degrees
angle_step = data_bw['x_rotation'][1] - data_bw['x_rotation'][0]
min_points = int( minimum_range_to_show / (angle_step.data * 180/np.pi) )

for z_id in (2, 10, N_z // 2, -1):
    this_t = R_frames['z'].isel(z=z_id).data
    
    fig_RCs, axes = plt.subplots(ncols=4, nrows=5, figsize=(12,18)) # 20 plots, sharex=True,

    for i, ax in enumerate(axes.ravel()):
        index = hkl_selection[i]
        reflection_hkl = str(data_bw['hkl'][index].data)

        # relevant alpha range with I > 0.02 * max(I)
        rocking_curve = data_bw.isel(z=z_id, hkl=index)
        angle_selection = (rocking_curve > (data_bw.isel(z=z_id, hkl=index).max().data * 0.02)).data
        significant_indices = np.argwhere( angle_selection ).flatten()
        first = significant_indices.min()
        last =  significant_indices.max()
        N_points = last - first
        if N_points >= min_points:
            selection = slice(first,last+1)
        else:
            first -= (min_points-N_points)//2
            last +=  (min_points-N_points)//2
            first = max(0,first)
            last = min(last, N_x-1)
            selection = slice(first,last+1)

        # plot
        ax.plot(data_bw['x_rotation'][selection]*180/np.pi, data_bw.isel(z=z_id, hkl=index).data[selection], label='BW '+reflection_hkl)
        ax.plot(data_ms['x_rotation'][selection]*180/np.pi, data_ms.isel(z=z_id, hkl=index).data[selection], '--', label='MS '+reflection_hkl)
        #ax.set_xlabel('rotation α (°)')
        #ax.set_ylabel('intensity')
        ax.ticklabel_format(style='sci', scilimits=(0,0), axis='y')
        ax.legend()
    fig_RCs.suptitle(f"intensity as function of rotation angle α (°), z = {data_bw['z'][z_id]:04.0f}Å")
    fig_RCs.tight_layout()

    if s['save_images']:
        name = f"rocking_curves_{this_t:.0f}"
        fig_RCs.savefig(export_base / (name+'.pdf'), format='pdf', dpi=300)
        fig_RCs.savefig(export_base / (name+'.png'), format='png', dpi=300)
    else:
        plt.show()
       
