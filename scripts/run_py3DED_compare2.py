        #print(f'    {s000.min():6.3f} {s000.max():6.3f} {s000.mean():6.3f} {s000.std():6.3f}    {d000.sum():10.4f}    {d000.mean():10.6f}  {d000.std():10.6f} {N_x*N_z:10d} based on 000')
        
